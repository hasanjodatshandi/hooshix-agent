#!/usr/bin/env node
/**
 * 14.9 — generate docs/TOOLS.md from the runtime catalog.
 *
 * The tool reference used to be hand-copied from the catalog. That is how the
 * original five-tool gap happened, and why the R9.06 contract test now checks
 * both directions by hand. This script is the generation half: it rewrites
 * docs/TOOLS.md from ALL_REGISTERED_TOOLS + OPERATION_CATALOG, so the document
 * cannot drift from the code that actually registers the tools.
 *
 * The test remains the gate: this script produces the file, the test proves it
 * matches the catalog in both directions, and a diff in CI is a review signal.
 *
 * Usage: node scripts/generate-tools-doc.mjs
 * Exit: 0 on success, 1 if the file would change (CI gate).
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { ALL_REGISTERED_TOOLS, CONTROL_TOOL_NAMES, OPERATION_CATALOG, TOOL_CATEGORIES } =
  require("../dist/application/services/operation-catalog.js");

const TARGET = path.resolve("docs/TOOLS.md");

function esc(name) {
  return "`" + name + "`";
}

function lines() {
  const out = [
    "# Tool Reference",
    "",
    "Generated by `scripts/generate-tools-doc.mjs` from `src/application/services/operation-catalog.ts`.",
    "Do not edit by hand — regenerate with `node scripts/generate-tools-doc.mjs`.",
    "",
    `Total: ${ALL_REGISTERED_TOOLS.length} tools — ${ALL_REGISTERED_TOOLS.length - CONTROL_TOOL_NAMES.length} step-executable and ${CONTROL_TOOL_NAMES.length} control.`,
    "",
    "Every tool is listed with its risk class, approval tag and workspace scope.",
    "Only the tool name in the first column is a registered operation name.",
    "",
  ];

  for (const category of TOOL_CATEGORIES) {
    const names = ALL_REGISTERED_TOOLS.filter((n) => OPERATION_CATALOG[n]?.category === category);
    if (names.length === 0) continue;
    out.push(`## ${category}`, "");
    out.push("| Tool | Risk | Approval | Scope |", "|---|---|---|---|");
    for (const name of names) {
      // Only the tool name is backticked, so a reader (or a contract test)
      // cannot mistake a risk class like "low" for a registered operation.
      const d = OPERATION_CATALOG[name];
      out.push(`| ${esc(name)} | ${d.risk} | ${d.approval} | ${d.workspaceScope} |`);
    }
    out.push("");
  }

  out.push("## Security classes", "");
  out.push("| Category | Class |", "|---|---|");
  for (const category of TOOL_CATEGORIES) {
    const classes = [
      ...new Set(ALL_REGISTERED_TOOLS.filter((n) => OPERATION_CATALOG[n]?.category === category).map((n) => OPERATION_CATALOG[n].securityClass)),
    ];
    out.push(`| ${category} | ${classes.join(", ")} |`);
  }
  out.push("");

  out.push("## Approval tags", "");
  out.push("- never — no operator approval needed for this tool.");
  out.push("- always — every invocation requires a verified, single-use approval bound to the exact task/step/args/scope.");
  out.push("- admin-and-approval — operator permission AND a verified approval.");
  out.push("");
  return out;
}

function main() {
  const next = lines().join("\n");
  const previous = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : "";
  if (previous === next) {
    process.stdout.write("docs/TOOLS.md is up to date.\n");
    process.exit(0);
  }
  if (process.env.CHECK) {
    process.stdout.write("docs/TOOLS.md is stale — run scripts/generate-tools-doc.mjs.\n");
    process.exit(1);
  }
  fs.writeFileSync(TARGET, next);
  process.stdout.write(`docs/TOOLS.md regenerated (${ALL_REGISTERED_TOOLS.length} tools).\n`);
  process.exit(0);
}

main();
